/** Percentage string → number, for the filters below. */
function pct(v: string): number {
  return parseFloat(v);
}

/**
 * Square field for < lg.
 *
 * Keeps the dust dense — only the tight band the headline actually occupies is
 * cleared, so nothing sits behind the words while the rest of the canvas stays
 * busy. The mirrored copies below fill the lower half, which the desktop
 * scatter leaves comparatively empty at phone proportions.
 */
const mobileClearZone = (s: Square) =>
  !(pct(s.y) > 4 && pct(s.y) < 34 && pct(s.x) < 62);

export const mobileSquares: Square[] = [
  ...squares.filter(mobileClearZone),
  // Mirrored duplicates need a unique React key but reuse the original's
  // @keyframes, hence `animId` — no extra CSS is generated for them.
  ...squares
    .filter((s, i) => i % 3 === 0 && pct(s.y) > 40)
    .map((s) => ({
      ...s,
      id: s.id + 1000,
      animId: s.id,
      x: `${Math.max(1, 96 - pct(s.x))}%`,
      y: `${Math.min(97, pct(s.y) + 8)}%`,
    })),
];

